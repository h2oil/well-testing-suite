#!/usr/bin/env node
// Packs the Modbus bridge (tools/modbus-bridge/) into prism-build/64-modbus-bridge-pack.js,
// a Round-10 file that defines
//
//   window.WTS_modbusBridgePack = { version, order: [names], files: { name: text }, sha256: { name: hex } }
//
// so the Modbus page's setup guide can offer the bridge package (.zip) and generate
// ready-to-run installers with no network access (the web app is one HTML file and may be
// used offline). Text is normalised to LF (a Windows CRLF checkout must not break install.sh);
// sha256 is over the UTF-8 bytes of that LF text — exactly the bytes the zip / installers write.
//
// Run with:  node prism-build/pack-modbus-bridge.js      (concat-round10.js also runs it first)
// require()-able: module.exports = { FILES, TOOLS, OUT, readFiles, bridgeVersion, sha256, build, main }.

'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const TOOLS = path.resolve(__dirname, '..', 'tools', 'modbus-bridge');
const OUT = path.join(__dirname, '64-modbus-bridge-pack.js');
const FILES = ['modbus-bridge.js', 'fake-slave.js', 'install-windows.ps1', 'install.sh', 'README.md'];

function normalise(text) { return String(text).replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n'); }
function readFiles(dir) {
  const out = {};
  for (const f of FILES) out[f] = normalise(fs.readFileSync(path.join(dir || TOOLS, f), 'utf8'));
  return out;
}
function bridgeVersion(src) {
  const m = /const BRIDGE_VERSION = '([0-9]+\.[0-9]+\.[0-9]+)';/.exec(src || '');
  if (!m) throw new Error('modbus-bridge.js has no BRIDGE_VERSION constant');
  return m[1];
}
function sha256(text) { return crypto.createHash('sha256').update(Buffer.from(text, 'utf8')).digest('hex'); }
// A JS string literal that is also safe inside an HTML <script> block.
function jsString(s) {
  return JSON.stringify(s).replace(/</g, '\\u003c').replace(/>/g, '\\u003e')
    .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function build(files) {
  files = files || readFiles();
  const version = bridgeVersion(files['modbus-bridge.js']);
  const L = [];
  L.push('// =============================================================================');
  L.push('// 64-modbus-bridge-pack.js — GENERATED by prism-build/pack-modbus-bridge.js from');
  L.push('// tools/modbus-bridge/ — do not edit; change the files there and run');
  L.push('//   node prism-build/pack-modbus-bridge.js   (concat-round10.js runs it too).');
  L.push('// window.WTS_modbusBridgePack = { version, order, files: { name: text }, sha256: { name: hex } }');
  L.push('// feeds the Modbus page\'s bridge setup guide (package download, generated installers)');
  L.push('// so it works offline. Text is LF; sha256 is over its UTF-8 bytes.');
  L.push('// =============================================================================');
  L.push('(function () {');
  L.push("'use strict';");
  L.push("var G = (typeof window !== 'undefined') ? window : globalThis;");
  L.push('G.WTS_modbusBridgePack = {');
  L.push('    version: ' + jsString(version) + ',');
  L.push('    order: ' + JSON.stringify(FILES) + ',');
  L.push('    sha256: {');
  FILES.forEach((f, i) => L.push('        ' + jsString(f) + ': ' + jsString(sha256(files[f])) + (i < FILES.length - 1 ? ',' : '')));
  L.push('    },');
  L.push('    files: {');
  FILES.forEach((f, i) => L.push('        ' + jsString(f) + ': ' + jsString(files[f]) + (i < FILES.length - 1 ? ',' : '')));
  L.push('    }');
  L.push('};');
  L.push('})();');
  L.push('');
  L.push('// === SELF-TEST ===');
  L.push('(function () {');
  L.push("    var G = (typeof window !== 'undefined') ? window : globalThis, P = G.WTS_modbusBridgePack;");
  L.push("    var ok = !!(P && P.version && P.order.every(function (f) { return typeof P.files[f] === 'string' && /^[0-9a-f]{64}$/.test(P.sha256[f]); }));");
  L.push("    if (typeof console !== 'undefined') console[ok ? 'log' : 'warn']('[64-modbus-bridge-pack] self-test ' + (ok ? 'passed' : 'FAILED'));");
  L.push('})();');
  L.push('');
  return L.join('\n');
}

function main(opts) {
  opts = opts || {};
  const log = opts.log || console;
  if (!fs.existsSync(path.join(TOOLS, 'modbus-bridge.js'))) { log.warn('[pack] ' + TOOLS + ' not found — pack left as it is'); return false; }
  const text = build();
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (old === text) { log.log('[pack] ' + path.basename(OUT) + ' is up to date'); return false; }
  fs.writeFileSync(OUT, text, 'utf8');
  log.log('[pack] wrote ' + OUT + ' (' + Math.round(text.length / 1024) + ' KB, bridge v' + bridgeVersion(readFiles()['modbus-bridge.js']) + ')');
  return true;
}

module.exports = { FILES, TOOLS, OUT, readFiles, bridgeVersion, sha256, build, main, normalise };
if (require.main === module) main();
