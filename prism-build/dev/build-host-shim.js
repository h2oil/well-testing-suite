#!/usr/bin/env node
// Dev-only (not injected, not shipped): builds the host shim used by
// prism-build/dev/wts-live-dev.html so the live controller can be iterated
// against the REAL (patched) Well Test Simulator page code without touching
// well-testing-app.html.
//
//   node prism-build/dev/build-host-shim.js
//
// Reads well-testing-app.html, applies prism-build/wts-host-patch.js IN MEMORY,
// extracts the "── Well Test Simulator ──" section (renderWTS, calcWTS,
// wtsDrawDiag + bridges) and the head <style> block, and writes:
//   prism-build/.tmp/wts-host-shim.js   (section wrapped with $/fmt/saveInputs/loadInputs stubs)
//   prism-build/.tmp/wts-host.css       (the app's theme + page CSS)
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'prism-build', '.tmp');
const { patch } = require('../wts-host-patch.js');

const html0 = fs.readFileSync(path.join(ROOT, 'well-testing-app.html'), 'utf8');
const { out: html, report } = patch(html0, {});
const bad = report.filter(r => !/^(applied|already)$/.test(r.status));
if (bad.length) { console.error('[shim] patch problems:', bad.map(b => b.id + ':' + b.status).join(', ')); process.exit(1); }
const t = html.replace(/\r\n/g, '\n');

const a = t.indexOf('// ── Well Test Simulator ──');
const b = t.indexOf('// ── Initial render ──', a);
if (a < 0 || b < 0) { console.error('[shim] WTS section not found'); process.exit(1); }
const section = t.slice(t.lastIndexOf('\n', a) + 1, b);

const s0 = t.indexOf('<style>'), s1 = t.indexOf('</style>', s0);
const css = t.slice(s0 + 7, s1);

const shim = [
  '// GENERATED by prism-build/dev/build-host-shim.js — do not edit. Dev-only host shim.',
  '(function () {',
  "'use strict';",
  'const $ = id => document.getElementById(id);',
  "const fmt = (v,d=2) => { if(v==null||isNaN(v)) return '\\u2014'; return Number(v).toLocaleString(undefined,{minimumFractionDigits:0,maximumFractionDigits:d}); };",
  "function saveInputs(key, ids) { try { const o = {}; ids.forEach(id => { const e = $(id); if (e) o[id] = e.value; }); localStorage.setItem('wtsdev_' + key, JSON.stringify(o)); } catch (e) {} }",
  "function loadInputs(key, ids) { try { const o = JSON.parse(localStorage.getItem('wtsdev_' + key) || '{}'); ids.forEach(id => { const e = $(id); if (e && o[id] != null) e.value = o[id]; }); } catch (e) {} }",
  section,
  'window.renderWTS = renderWTS;',
  '})();',
  ''].join('\n');

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'wts-host-shim.js'), shim, 'utf8');
fs.writeFileSync(path.join(OUT, 'wts-host.css'), '/* GENERATED from well-testing-app.html <style> — dev only */\n' + css, 'utf8');
console.log('[shim] wrote prism-build/.tmp/wts-host-shim.js (' + shim.split('\n').length + ' lines) and wts-host.css');
