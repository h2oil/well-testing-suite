#!/usr/bin/env node
'use strict';
// server/site/netlify-check.js — the build command of the functions site (server/netlify.toml). It builds nothing; it refuses
// a deploy that breaks the site's rules, so a mistake fails the deploy instead of going live (v4.0; README "Hosting"):
//   • the publish directory holds robots.txt and nothing else (the site publishes no content);
//   • netlify/functions holds exactly the six functions of site/netlify.js FUNCTIONS, each with its literal config;
//   • no file of the bundle (core/, functions/, site/, netlify/, public/, netlify.toml) contains key material or a secret
//     value pattern (ci/secret-scan.js rules);
//   • Node is at least 22.12 (the blob store package needs it).
//
//   node site/netlify-check.js   → "[netlify-check] ok …" or the problems and exit 1
//   require('./netlify-check').check(root?) → [problems]
//
// LIVE layout (`--live`; the build command of the bundle server/site/build-live.js writes for the live site
// welltest.h2oil.co.uk, same-site mode — server/RUNBOOK.md "Live site (same-site) setup"): checkLive(root, {uploaded}) →
// [problems]. The bundle holds ONLY the files of LIVE (below); public/ holds exactly the files of public/publish-manifest.json
// (prism-build/publish-site.js; every hash must match; index.html, well-testing-app.html and sw.js present) plus _headers and
// the manifest; netlify/functions holds the functions of one live layout with their live config (site/netlify.js functionsFor /
// functionSource: 'live' = six with the background functions, the default, or the opt-in 'live-inline' = four);
// netlify/database/migrations holds the platform migrations; netlify.toml is exactly LIVE_TOML; no key file, PEM / JWK private
// key or secret value anywhere (ci/secret-scan.js rules on every server text file). uploaded:true (build-live.js --check on the
// lead's computer) also refuses node_modules/ and dot folders; on the platform (the build command) the installed
// node_modules/ and the platform's own dot folders are skipped.

const fs = require('fs');
const path = require('path');

const SERVER = path.join(__dirname, '..');
const SCAN_DIRS = ['core', 'functions', 'site', 'netlify', 'public'];

function walk(dir, rel, out) {
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).forEach((d) => {
    const r = rel ? rel + '/' + d.name : d.name;
    if (d.isDirectory()) walk(path.join(dir, d.name), r, out);
    else if (d.isFile()) out.push(r);
  });
  return out;
}
// the literal `export const config = {...}` of an entry file ({} when absent)
function literalConfig(text) {
  const m = /export const config = (\{[^;]*\});/.exec(text);
  if (!m) return null;
  return Function('"use strict"; return (' + m[1] + ');')();
}

function check(root) {
  root = root || SERVER;
  const problems = [];
  const { FUNCTIONS } = require('./netlify');
  const pub = fs.existsSync(path.join(root, 'public')) ? fs.readdirSync(path.join(root, 'public')) : [];
  if (pub.length !== 1 || pub[0] !== 'robots.txt') problems.push('public/ must hold robots.txt only');
  const fnDir = path.join(root, 'netlify', 'functions');
  const files = fs.existsSync(fnDir) ? fs.readdirSync(fnDir).sort() : [];
  const want = Object.keys(FUNCTIONS).map((k) => FUNCTIONS[k].file).sort();
  if (JSON.stringify(files) !== JSON.stringify(want)) problems.push('netlify/functions must hold exactly ' + want.join(', '));
  Object.keys(FUNCTIONS).forEach((name) => {
    const f = path.join(fnDir, FUNCTIONS[name].file);
    if (!fs.existsSync(f)) return;
    const text = fs.readFileSync(f, 'utf8');
    let cfg;
    try { cfg = literalConfig(text); } catch (e) { problems.push(name + ': config is not a literal'); return; }
    if (JSON.stringify(cfg) !== JSON.stringify(FUNCTIONS[name].config)) problems.push(name + ': config differs from site/netlify.js FUNCTIONS');
    if (!/^import nf from '\.\.\/\.\.\/site\/netlify\.js';$/m.test(text)) problems.push(name + ': must import site/netlify.js');
  });
  const scan = require('../ci/secret-scan');
  const list = SCAN_DIRS.reduce((acc, d) => walk(path.join(root, d), d, acc), []).concat(['netlify.toml']);
  list.forEach((r) => {
    const f = path.join(root, r);
    if (!fs.existsSync(f)) return;
    if (scan.KEY_FILE.test(r)) problems.push(r + ': key file');
    if (/\.(m?js|json|toml|txt|sql)$/.test(r)) scan.scanText(fs.readFileSync(f, 'utf8')).forEach((x) => problems.push(r + ':' + x.line + ' ' + x.rule));
  });
  const [maj, min] = process.versions.node.split('.').map(Number);
  if (maj < 22 || (maj === 22 && min < 12)) problems.push('Node ' + process.versions.node + ' is older than 22.12');
  return problems;
}

// ── the live bundle ──────────────────────────────────────────────────────────────────────────────────────────────
const LIVE_TOML = [
  '# netlify.toml — GENERATED by server/site/build-live.js: the LIVE site welltest.h2oil.co.uk with the web accounts API in',
  '# same-site mode (server/RUNBOOK.md "Live site (same-site) setup"). It never holds a secret: every secret is an environment',
  '# variable of the site (scope Functions, deploy context Production). Static files win for every path; the API function owns',
  '# /api/v1/* only. package.json depends on @netlify/database, so a production deploy applies netlify/database/migrations before',
  '# it publishes (never edit or remove an applied file). A failed build or migration never replaces the live version.',
  '',
  '[build]',
  '  # nothing to build: the command refuses a broken or incomplete bundle (site/netlify-check.js --live)',
  '  command = "node site/netlify-check.js --live"',
  '  publish = "public"',
  '',
  '[build.environment]',
  '  NODE_VERSION = "22"',
  '  NPM_FLAGS = "--omit=dev --ignore-scripts"',
  '',
  '[functions]',
  '  directory = "netlify/functions"',
  '  node_bundler = "nft"',
  '  # loaded with a plain require() at run time, which the tracer can miss: ship them as they are',
  '  external_node_modules = ["@netlify/blobs", "postgres", "@netlify/database"]',
  '  included_files = ["core/**", "functions/**", "site/*.js", "db/migrate.js", "package.json"]',
  '',
].join('\n');
// the server files of the bundle (the runtime closure of the six functions + this check)
const LIVE_SITE_FILES = ['adapters.js', 'backup.js', 'handler.js', 'isolation.js', 'monitor.js', 'netlify.js', 'netlify-blobs.js',
  'netlify-check.js', 'objects-loader.js', 'ops-env.js'];
const LIVE_ROOT_FILES = ['netlify.toml', 'package.json', 'package-lock.json', 'build-info.json'];
const LIVE_PUBLIC_REQUIRED = ['index.html', 'well-testing-app.html', 'sw.js'];
const PUBLIC_FORBIDDEN = [/\.sql$/i, /(^|\/)\.env($|\.)/i, /\.(pem|key|jwk|p12|pfx)$/i, /(^|\/)id_(rsa|ed25519|ecdsa)/i,
  /(^|\/)package(-lock)?\.json$/i, /\.(test|spec)\.js$/i, /^(server|docs|tools|prism-build|ios-app|wiki|netlify|core|functions|site|db|ci)\//];
const MIGRATION_RE = /^netlify\/database\/migrations\/\d{4}_[a-z0-9_]+\.sql$/;
const PEM_PRIVATE = new RegExp('-----BEGIN ' + '(?:[A-Z]+ )?PRIVATE ' + 'KEY-----');

function liveAllowed(rel) {
  if (LIVE_ROOT_FILES.indexOf(rel) !== -1) return true;
  if (/^core\/[a-z0-9-]+\.js$/.test(rel) || /^functions\/[a-z0-9-]+\.js$/.test(rel)) return true;
  if (rel === 'db/migrate.js' || rel === 'ci/secret-scan.js') return true;
  if (/^site\//.test(rel)) return LIVE_SITE_FILES.indexOf(rel.slice(5)) !== -1;
  if (MIGRATION_RE.test(rel)) return true;
  if (/^netlify\/functions\/[a-z0-9-]+\.mjs$/.test(rel)) return true;
  if (/^public\//.test(rel)) return true;                       // checked against the manifest below
  return false;
}
function walkAll(dir, rel, out, skip) {
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1)).forEach((d) => {
    const r = rel ? rel + '/' + d.name : d.name;
    if (skip && skip(r, d)) return;
    if (d.isSymbolicLink()) { out.push({ rel: r, link: true }); return; }
    if (d.isDirectory()) walkAll(path.join(dir, d.name), r, out, skip);
    else if (d.isFile()) out.push({ rel: r });
  });
  return out;
}
function sha256(buf) { return require('crypto').createHash('sha256').update(buf).digest('hex'); }

// → {problems, files} for the live bundle at root
function checkLive(root, o) {
  o = o || {};
  const problems = [];
  if (!root || !fs.existsSync(root)) return { problems: ['bundle folder missing'], files: [] };
  // on the platform: the installed packages and the platform's own folders (.netlify …) are not part of the upload
  const skip = o.uploaded ? null : (r) => r === 'node_modules' || /^\.[^/]+$/.test(r);
  const files = walkAll(root, '', [], skip);
  const scan = require('../ci/secret-scan');
  const { functionsFor, functionSource } = require('./netlify');
  files.forEach((f) => {
    if (f.link) { problems.push(f.rel + ': symbolic link'); return; }
    if (f.rel.split('/').some((p) => p.startsWith('.'))) problems.push(f.rel + ': dot file or folder');
    if (scan.KEY_FILE.test(f.rel)) problems.push(f.rel + ': key file');
    if (!liveAllowed(f.rel)) problems.push(f.rel + ': not in the bundle allow-list');
  });
  const have = new Set(files.map((f) => f.rel));
  LIVE_ROOT_FILES.forEach((r) => { if (!have.has(r)) problems.push(r + ': missing'); });
  ['core/config.js', 'core/app.js', 'functions/index.js', 'db/migrate.js', 'ci/secret-scan.js'].concat(LIVE_SITE_FILES.map((n) => 'site/' + n))
    .forEach((r) => { if (!have.has(r)) problems.push(r + ': missing'); });
  // netlify.toml exactly the generated one
  if (have.has('netlify.toml') && fs.readFileSync(path.join(root, 'netlify.toml'), 'utf8') !== LIVE_TOML) problems.push('netlify.toml differs from the generated live configuration');
  // package.json: the server's pinned runtime dependencies, the database package included
  if (have.has('package.json')) {
    let pkg = null;
    try { pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')); } catch (e) { problems.push('package.json: not JSON'); }
    const deps = (pkg && pkg.dependencies) || {};
    ['@netlify/database', '@netlify/blobs', 'postgres'].forEach((d) => { if (!/^\d+\.\d+\.\d+$/.test(String(deps[d] || ''))) problems.push('package.json: ' + d + ' must be pinned to an exact version'); });
    if (pkg && (pkg.devDependencies || pkg.scripts)) problems.push('package.json: no scripts or development dependencies in the live bundle');
  }
  // functions: exactly the set of one live layout ('live', the default: the six with the two background functions;
  // 'live-inline', opt-in: four, the jobs inside the scheduled functions), each the generated live source
  const fnFiles = files.filter((f) => /^netlify\/functions\//.test(f.rel)).map((f) => f.rel.slice('netlify/functions/'.length)).sort();
  const setOf = (L) => Object.keys(L).map((k) => L[k].file).sort();
  const layout = fnFiles.some((f) => /-background\.mjs$/.test(f)) ? 'live' : 'live-inline';
  const LF = functionsFor(layout);
  const want = setOf(LF);
  if (JSON.stringify(fnFiles) !== JSON.stringify(want)) problems.push('netlify/functions must hold exactly ' + want.join(', ') + ' (layout ' + layout + ')');
  Object.keys(LF).forEach((name) => {
    const f = path.join(root, 'netlify', 'functions', LF[name].file);
    if (!fs.existsSync(f)) return;
    const text = fs.readFileSync(f, 'utf8');
    if (text !== functionSource(name, layout)) problems.push(name + ': differs from the generated live function');
    let cfg = null; try { cfg = literalConfig(text); } catch (e) { cfg = null; }
    if (JSON.stringify(cfg) !== JSON.stringify(LF[name].config)) problems.push(name + ': config differs from functionsFor(' + layout + ')');
  });
  if (!LF.api || LF.api.config.path !== '/api/v1/*') problems.push('api: the path must be /api/v1/*');
  // migrations: at least the platform role file and the schema
  const migs = files.filter((f) => MIGRATION_RE.test(f.rel)).map((f) => f.rel);
  if (!migs.some((m) => /\/0000_/.test(m)) || migs.length < 2) problems.push('netlify/database/migrations: the platform migrations are missing');
  // public/: exactly the manifest, hashes equal, nothing forbidden
  const pub = files.filter((f) => /^public\//.test(f.rel)).map((f) => f.rel.slice(7));
  let man = null;
  try { man = JSON.parse(fs.readFileSync(path.join(root, 'public', 'publish-manifest.json'), 'utf8')); } catch (e) { problems.push('public/publish-manifest.json: missing or not JSON'); }
  if (man) {
    const listed = new Map(); (man.files || []).forEach((x) => listed.set(String(x.path), x));
    pub.forEach((r) => {
      if (r === '_headers' || r === 'publish-manifest.json') return;
      const m = listed.get(r);
      if (!m) { problems.push('public/' + r + ': not in publish-manifest.json'); return; }
      const b = fs.readFileSync(path.join(root, 'public', r));
      if (b.length !== m.bytes || sha256(b) !== m.sha256) problems.push('public/' + r + ': differs from publish-manifest.json');
    });
    listed.forEach((m, r) => { if (pub.indexOf(r) === -1) problems.push('public/' + r + ': listed but missing'); });
    LIVE_PUBLIC_REQUIRED.forEach((r) => { if (!listed.has(r)) problems.push('public/' + r + ': required'); });
  }
  if (pub.indexOf('_headers') === -1) problems.push('public/_headers: missing');
  pub.forEach((r) => { const bad = PUBLIC_FORBIDDEN.find((re) => re.test(r)); if (bad) problems.push('public/' + r + ': forbidden in the publish folder'); });
  // secret values: every server text file (rules of ci/secret-scan.js); PEM private keys anywhere, the published files included
  files.forEach((f) => {
    if (f.link) return;
    const abs = path.join(root, f.rel);
    if (/^public\//.test(f.rel)) {
      if (/\.(html?|js|json|txt|css|svg|xml|webmanifest)$/i.test(f.rel) && PEM_PRIVATE.test(fs.readFileSync(abs, 'utf8'))) problems.push(f.rel + ': PEM private key');
      return;
    }
    if (/\.(m?js|json|toml|sql|txt)$/.test(f.rel)) scan.scanText(fs.readFileSync(abs, 'utf8')).forEach((x) => problems.push(f.rel + ':' + x.line + ' ' + x.rule));
  });
  const [maj, min] = process.versions.node.split('.').map(Number);
  if (maj < 22 || (maj === 22 && min < 12)) problems.push('Node ' + process.versions.node + ' is older than 22.12');
  return { problems, files: files.map((f) => f.rel), layout };
}

module.exports = { check, checkLive, literalConfig, LIVE_TOML, LIVE_SITE_FILES, LIVE_ROOT_FILES, liveAllowed };

if (require.main === module && process.argv.includes('--live')) {
  const r = checkLive(SERVER);
  if (r.problems.length) { console.error('[netlify-check] live bundle refused:\n  ' + r.problems.join('\n  ')); process.exit(1); }
  console.log('[netlify-check] ok — live bundle: ' + r.files.length + ' files, layout ' + r.layout + ' (same-site), publish folder = manifest, no key material, Node ' + process.versions.node);
} else if (require.main === module) {
  const p = check();
  if (p.length) { console.error('[netlify-check] refused:\n  ' + p.join('\n  ')); process.exit(1); }
  console.log('[netlify-check] ok — publish directory, six functions, no key material, Node ' + process.versions.node);
}
