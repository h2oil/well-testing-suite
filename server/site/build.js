#!/usr/bin/env node
'use strict';
// server/site/build.js — builds the functions-only site bundle server/dist/ (docs/ACCOUNTS-PLAN.md §13.1, §13.8; WP-OPS).
// Run by the tagged release workflow (server-v* tags only); git-ignored output.
//
//   node server/site/build.js [--out <dir>]
//
// dist/ holds: core/, functions/ (the route-table modules exporting {handlers} — NOT host functions), db/ (migrations +
// migrate.js), site/ (adapter, isolation, monitor, adapters, objects-loader and, when committed, the owner's
// site/objects-binding.js — it reads its credential from the environment, so it survives every rebuild from the repository),
// package.json + package-lock.json (production dependencies are installed by the workflow with `npm ci --omit=dev` in dist),
// entry/api.js — the ONLY host function, alone in its own folder so a host that deploys every file of its functions folder
// deploys just this one (default export for fetch-style runtimes, `handler` for event-style runtimes) — and
// static/robots.txt (the only static file: "Disallow: /"; the site publishes no app content), build-info.json (the tag,
// the commit and the SHA-256 of every file). It never contains test/, ops/ scripts, ci/, the RUNBOOK, .env* or keys; the build
// fails if a file in dist names a secret VALUE pattern (server/ci/secret-scan.js rules) or if the static folder holds
// anything but robots.txt.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SERVER = path.join(__dirname, '..');
const COPY = ['core', 'functions', 'db', 'site'];
const SKIP = /(^|\/)(test|node_modules|dist|\.env[^/]*|[^/]+\.(pem|key|jwk|p12))(\/|$)/;

function copyTree(src, dst, rel, list) {
  fs.mkdirSync(dst, { recursive: true });
  fs.readdirSync(src, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1)).forEach((d) => {
    const r = rel ? rel + '/' + d.name : d.name;
    if (SKIP.test(r) || d.name.startsWith('.') || d.isSymbolicLink()) return;
    if (d.isDirectory()) copyTree(path.join(src, d.name), path.join(dst, d.name), r, list);
    else if (d.isFile()) { fs.copyFileSync(path.join(src, d.name), path.join(dst, d.name)); list.push(r); }
  });
}
const ENTRY = `'use strict';
// GENERATED by server/site/build.js — the functions-only site's single function (all of /api/v1/*).
// The blob store comes from site/objects-loader.js (WTS_OBJECTS_BINDING, else site/objects-binding.js, else WTS_OBJECTS_DIR).
const { createHandler } = require('../site/handler');
const h = createHandler({ env: process.env });
async function api(request, context) { return h.handle(request, context); }
module.exports = api;
module.exports.default = api;
module.exports.handler = (event) => h.classic(event);
module.exports.config = { path: '/api/v1/*' };
`;

function build(o) {
  o = o || {};
  const out = path.resolve(o.out || path.join(SERVER, 'dist'));
  if (!out.startsWith(SERVER + path.sep) && !o.allowOutside) throw new Error('site/build: --out must be inside server/');
  fs.rmSync(out, { recursive: true, force: true });
  const list = [];
  COPY.forEach((d) => copyTree(path.join(SERVER, d), path.join(out, d), d, list));
  ['package.json', 'package-lock.json'].forEach((f) => { fs.copyFileSync(path.join(SERVER, f), path.join(out, f)); list.push(f); });
  fs.mkdirSync(path.join(out, 'entry'), { recursive: true });
  fs.writeFileSync(path.join(out, 'entry', 'api.js'), ENTRY); list.push('entry/api.js');
  const entries = fs.readdirSync(path.join(out, 'entry'));
  fs.mkdirSync(path.join(out, 'static'), { recursive: true });
  fs.writeFileSync(path.join(out, 'static', 'robots.txt'), 'User-agent: *\nDisallow: /\n'); list.push('static/robots.txt');
  // checks
  const scan = require('../ci/secret-scan');
  const bad = [];
  list.forEach((r) => {
    const f = path.join(out, r);
    if (/\.(js|json|sql|txt)$/.test(r)) scan.scanText(fs.readFileSync(f, 'utf8')).forEach((x) => bad.push(r + ':' + x.line + ' ' + x.rule));
    if (scan.KEY_FILE.test(r)) bad.push(r + ' key-file');
  });
  const statics = fs.readdirSync(path.join(out, 'static'));
  if (statics.length !== 1 || statics[0] !== 'robots.txt') bad.push('static/ holds more than robots.txt');
  if (entries.length !== 1 || entries[0] !== 'api.js') bad.push('entry/ holds more than api.js');
  if (bad.length) { fs.rmSync(out, { recursive: true, force: true }); throw new Error('site/build: refused — ' + bad.join('; ')); }
  const files = list.sort().map((r) => ({ path: r, sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join(out, r))).digest('hex') }));
  const info = { tag: process.env.GITHUB_REF_NAME || o.tag || null, commit: process.env.GITHUB_SHA || o.commit || null, files };
  fs.writeFileSync(path.join(out, 'build-info.json'), JSON.stringify(info, null, 1) + '\n');
  return { out, files: list.length, info };
}

module.exports = { build, ENTRY };

if (require.main === module) {
  const a = process.argv.slice(2); const i = a.indexOf('--out');
  try { const r = build({ out: i !== -1 ? a[i + 1] : null }); console.log('[site/build] ' + r.files + ' files → ' + path.relative(process.cwd(), r.out)); }
  catch (e) { console.error('[site/build] ' + e.message); process.exit(1); }
}
