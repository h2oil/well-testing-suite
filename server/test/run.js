#!/usr/bin/env node
'use strict';
// server/test/run.js — the server test runner (docs/ACCOUNTS-PLAN.md §12.4).
//
//   node server/test/run.js [--no-db] [--schema] [file-substring …]
//
// Boots a throwaway database cluster (test/_cluster.js; port WTS_TEST_DB_PORT, default 54010), creates the database
// 'wts_test', exports its connection as WTS_TEST_DB (JSON) and runs `node --test` over server/test/*.test.js. Tests that need
// the database skip themselves when WTS_TEST_DB is absent (--no-db, or no engine binaries on the machine). The cluster is
// stopped and its folder deleted on exit, also after a failure.
//   --schema  instead regenerates server/db/schema.sql (a schema-only dump of a freshly migrated database, header lines
//             stripped) for review, then exits.

const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const cluster = require('./_cluster');

const DIR = __dirname;
const args = process.argv.slice(2);
const noDb = args.includes('--no-db');
const schemaOnly = args.includes('--schema');
const filters = args.filter((a) => !a.startsWith('--'));

async function createDatabase(conn, name) {
  const { createDb } = require('../core/db');
  const db = createDb(conn, { max: 1 });
  try { await db.sql.unsafe('CREATE DATABASE ' + name); } finally { await db.close(); }
  return Object.assign({}, conn, { database: name });
}

async function writeSchema(c, conn) {
  const { createDb } = require('../core/db');
  const { migrate } = require('../db/migrate');
  const db = createDb(conn, { max: 1 });
  try { await migrate(db.sql); } finally { await db.close(); }
  const bin = cluster.findBin();
  const r = cp.spawnSync(path.join(bin, 'pg_dump'), ['-h', conn.host, '-p', String(conn.port), '-U', conn.user, '-s', '-n', 'wts', '--no-tablespaces', conn.database], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error('schema dump failed: ' + r.stderr);
  const lines = r.stdout.split('\n').filter((l) => !/^--\s*(Dumped|Started|Completed|Name:|\S+ database dump|$)/.test(l) &&!/^\\(un)?restrict /.test(l) && !/^SELECT pg_catalog\.set_config\('search_path'/.test(l));
  const text = '-- server/db/schema.sql — GENERATED by `node server/test/run.js --schema` from server/db/migrations (review only;\n' +
    '-- never applied, never edited by hand).\n' + lines.join('\n').replace(/\n{3,}/g, '\n\n');
  fs.writeFileSync(path.join(DIR, '..', 'db', 'schema.sql'), text);
  console.log('[schema] wrote server/db/schema.sql (' + text.split('\n').length + ' lines)');
}

async function main() {
  let c = null;
  const env = Object.assign({}, process.env);
  delete env.WTS_TEST_DB;
  try {
    if (!noDb) {
      try {
        c = cluster.start({ log: (m) => console.log(m) });
        env.WTS_TEST_DB = JSON.stringify(await createDatabase(c.conn, 'wts_test'));
        env.WTS_TEST_DB_ADMIN = JSON.stringify(c.conn);
      } catch (e) {
        if (schemaOnly) throw e;
        console.log('[run] no database cluster (' + e.message.split('\n')[0] + ') — database tests will skip');
      }
    }
    if (schemaOnly) { await writeSchema(c, JSON.parse(env.WTS_TEST_DB)); return 0; }
    const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.test.js')).filter((f) => !filters.length || filters.some((s) => f.includes(s)))
      .sort().map((f) => path.join(DIR, f));
    const r = cp.spawnSync(process.execPath, ['--test', '--test-concurrency=1'].concat(files), { stdio: 'inherit', env, cwd: path.join(DIR, '..') });
    return r.status == null ? 1 : r.status;
  } finally {
    if (c) c.stop();
  }
}

main().then((code) => process.exit(code), (e) => { console.error('[run] ' + e.message); process.exit(1); });
